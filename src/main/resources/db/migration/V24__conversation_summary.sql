-- B2 : résumé persisté des tours anciens d'une conversation (mémoire conversationnelle). chat_history reste la source
-- de vérité ; le résumé couvre les messages jusqu'à covered_message_uuid inclus (ignoré si ce message n'existe plus).
CREATE TABLE conversation_summary (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uuid            VARCHAR(255) NOT NULL,
    conversation_uuid    VARCHAR(255) NOT NULL,
    covered_message_uuid VARCHAR(255) NOT NULL,
    summary              TEXT         NOT NULL,
    prompt_version       VARCHAR(64)  NOT NULL,
    prompt_tokens        INTEGER,
    completion_tokens    INTEGER,
    updated_at           TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_conversation_summary UNIQUE (user_uuid, conversation_uuid)
);
